use std::path::{Path, PathBuf};

use rmlx_server::chat_template::{
    load_template_source, ChatMessageTpl, ChatTemplate, RenderError, RenderOpts,
};

// ── Fixture type ──────────────────────────────────────────────────────────────

#[derive(serde::Deserialize, Debug)]
struct Fixture {
    snapshots: Vec<String>,
    // arch is present in the JSON for documentation purposes; not used at runtime.
    #[allow(dead_code)]
    arch: String,
    messages: Vec<FixtureMessage>,
    tools: Option<Vec<serde_json::Value>>,
    add_generation_prompt: bool,
    bos_token: String,
    eos_token: String,
    #[serde(default)]
    template_kwargs: serde_json::Map<String, serde_json::Value>,
    /// The HF render, or `None` when the template refuses the fixture.
    expected: Option<String>,
    /// The message of the template's refusal.
    expected_error: Option<String>,
}

#[derive(serde::Deserialize, Debug)]
struct FixtureMessage {
    role: String,
    content: String,
}

// ── Helpers ────────────────────────────────────────────────────────────────────

fn fixture_dir() -> PathBuf {
    // `tests/chat_template_fixtures/` lives next to this file.
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("chat_template_fixtures")
}

fn o_models_root() -> PathBuf {
    std::env::var_os("RMLX_O_MODELS_ROOT").map_or_else(|| PathBuf::from("models"), PathBuf::from)
}

/// Load a single fixture from the fixtures directory by filename stem.
fn load_fixture(stem: &str) -> Fixture {
    let path = fixture_dir().join(format!("{stem}.json"));
    let data = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("cannot read fixture {stem}.json: {e}"));
    serde_json::from_str(&data).unwrap_or_else(|e| panic!("cannot parse fixture {stem}.json: {e}"))
}

/// Run a single round-trip assertion on every listed snapshot that is present.
///
/// Returns `true` if the test ran on at least one. When none is present it
/// prints one named `SKIP` on stdout and returns `false`.
fn run_fixture(stem: &str) -> bool {
    let fixture = load_fixture(stem);
    let mut ran = false;
    for snapshot in &fixture.snapshots {
        ran |= assert_on_snapshot(stem, &fixture, snapshot);
    }
    if !ran {
        println!(
            "SKIP roundtrip_{stem}: none of {:?} present with a chat_template.jinja",
            fixture.snapshots
        );
    }
    ran
}

/// Render the fixture with the template of one snapshot and assert it. Returns
/// `false` when the snapshot is absent or ships no `chat_template.jinja`.
fn assert_on_snapshot(stem: &str, fixture: &Fixture, snapshot: &str) -> bool {
    let snap_dir = o_models_root().join(snapshot);

    if !snap_dir.exists() {
        eprintln!("{stem}: snapshot {snapshot} absent");
        return false;
    }

    // Some snapshots (e.g. ReaderLM-v2) embed the template in tokenizer_config.json
    // rather than a separate chat_template.jinja. rMLX currently requires the
    // .jinja file; skip gracefully when it's absent rather than panicking.
    let source = if let Ok(s) = load_template_source(&snap_dir) {
        s
    } else {
        eprintln!("{stem}: snapshot {snapshot} has no chat_template.jinja");
        return false;
    };
    let tpl = ChatTemplate::new(source)
        .unwrap_or_else(|e| panic!("{stem} on {snapshot}: cannot compile template: {e}"));

    let msgs: Vec<ChatMessageTpl<'_>> = fixture
        .messages
        .iter()
        .map(|m| ChatMessageTpl {
            role: m.role.as_str(),
            content: m.content.as_str(),
            ..Default::default()
        })
        .collect();

    let empty_tools: Vec<serde_json::Value> = vec![];
    let tools_slice = fixture.tools.as_deref().unwrap_or(&empty_tools);

    let opts = RenderOpts {
        bos_token: fixture.bos_token.as_str(),
        eos_token: fixture.eos_token.as_str(),
        add_generation_prompt: fixture.add_generation_prompt,
        tools: tools_slice,
        variables: Some(&fixture.template_kwargs),
    };

    match (
        tpl.render(&msgs, &opts),
        &fixture.expected,
        &fixture.expected_error,
    ) {
        (Ok(rendered), Some(expected), None) => assert_eq!(
            &rendered.text, expected,
            "{stem} on {snapshot}: render diverges from HF reference.\n  got:      {:?}\n  expected: {expected:?}",
            rendered.text,
        ),
        (Err(RenderError::Rejected(msg)), None, Some(expected_error)) => {
            assert_eq!(
                &msg, expected_error,
                "{stem} on {snapshot}: the template refuses with another message"
            );
        }
        (got, expected, expected_error) => {
            panic!(
                "{stem} on {snapshot}: want render {expected:?} / refusal {expected_error:?}, got {got:?}"
            )
        }
    }

    true
}

