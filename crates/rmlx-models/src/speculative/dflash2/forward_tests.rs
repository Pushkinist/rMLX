/// The three reference cases are far enough apart that matching all of them is
/// not something a forward ignoring the window or the context could do.
///
/// Without this the parity assertions below could all hold on a port that
/// silently dropped the sliding window, because the fixture would not be able
/// to tell.
#[test]
fn the_reference_cases_are_further_apart_than_the_tolerance() {
    let file = reference_file();
    let cases = ["hidden_wide", "hidden_window_trims", "hidden_short_context"];
    for (i, a) in cases.iter().enumerate() {
        for b in cases.iter().skip(i + 1) {
            let diff = max_abs_diff(&fixture_tensor(&file, a), &fixture_tensor(&file, b));
            assert!(
                diff > REFERENCE_TOL * 5.0,
                "{a} and {b} differ by only {diff}; a fixture this close cannot \
                 separate a port that ignores the window from one that does not"
            );
        }
    }
}

/// The whole stack reproduces the reference forward: the conditioning
/// projection, both convolutions per layer, attention over context and block,
/// RoPE, the MLP and the final norm.
#[test]
fn the_stack_reproduces_the_reference_forward() {
    let file = reference_file();
    let block = fixture_tensor(&file, "block_hidden");
    let ctx = fixture_tensor(&file, "target_hidden");
    let (drafter, _dir) = scale_drafter(None);

    let got = match drafter.forward_hidden(&block, &ctx) {
        Ok(a) => a,
        Err(e) => panic!("forward_hidden: {e}"),
    };
    let want = fixture_tensor(&file, "hidden_wide");
    assert_eq!(got.shape(), want.shape());
    let diff = max_abs_diff(&got, &want);
    assert!(
        diff <= REFERENCE_TOL,
        "the stack differs from the reference by {diff}"
    );
}

/// Conditioning rows older than the attention window are dropped, and the rows
/// that survive are masked exactly as far back as the window reaches.
///
/// At window 4 over 6 conditioning rows the reference keeps 3 and masks one
/// more of them per block position; a port that kept all 6, or kept 3 and
/// masked none, lands 0.6 away.
#[test]
fn the_window_drops_the_conditioning_rows_the_reference_drops() {
    let file = reference_file();
    let block = fixture_tensor(&file, "block_hidden");
    let ctx = fixture_tensor(&file, "target_hidden");
    let (drafter, _dir) = scale_drafter(Some(4));

    let got = match drafter.forward_hidden(&block, &ctx) {
        Ok(a) => a,
        Err(e) => panic!("forward_hidden: {e}"),
    };
    let diff = max_abs_diff(&got, &fixture_tensor(&file, "hidden_window_trims"));
    assert!(
        diff <= REFERENCE_TOL,
        "the windowed stack differs from the reference by {diff}"
    );
}

/// A conditioning context shorter than the block is the reference's answer too:
/// nothing in the mask or the position arithmetic assumes the context is the
/// longer of the two.
#[test]
fn a_context_shorter_than_the_block_matches_the_reference() {
    let file = reference_file();
    let block = fixture_tensor(&file, "block_hidden");
    let ctx = fixture_tensor(&file, "target_hidden_short");
    let (drafter, _dir) = scale_drafter(None);

    let got = match drafter.forward_hidden(&block, &ctx) {
        Ok(a) => a,
        Err(e) => panic!("forward_hidden: {e}"),
    };
    let diff = max_abs_diff(&got, &fixture_tensor(&file, "hidden_short_context"));
    assert!(
        diff <= REFERENCE_TOL,
        "a short context differs from the reference by {diff}"
    );
}

/// An input at a shape the config does not predict is refused, naming the input
/// and what was wanted.
#[test]
fn an_input_the_config_does_not_predict_is_refused() {
    let file = reference_file();
    let block = fixture_tensor(&file, "block_hidden");
    let ctx = fixture_tensor(&file, "target_hidden");
    let (drafter, _dir) = scale_drafter(None);

    // The conditioning is as wide as one target layer, not all of them — what a
    // caller that forgot to concatenate produces.
    let one_layer = match ctx.slice(&[0, 0, 0], &[1, 6, 64], &[1, 1, 1], Device::Cpu) {
        Ok(a) => a,
        Err(e) => panic!("slice: {e}"),
    };
    let err = match drafter.forward_hidden(&block, &one_layer) {
        Ok(_) => panic!("a conditioning input one layer wide must be refused"),
        Err(e) => e.to_string(),
    };
    assert!(
        err.contains("target_hidden") && err.contains("128"),
        "the refusal must name the input and the width it wanted: {err}"
    );

    // A block with no batch axis is the other shape a caller gets wrong.
    let rank_two = match block.reshape(&[4, 64], Device::Cpu) {
        Ok(a) => a,
        Err(e) => panic!("reshape: {e}"),
    };
    let err = match drafter.forward_hidden(&rank_two, &ctx) {
        Ok(_) => panic!("a rank-2 block must be refused"),
        Err(e) => e.to_string(),
    };
    assert!(
        err.contains("block") && err.contains("rank-3"),
        "the refusal must name the input and the rank it wanted: {err}"
    );
}
