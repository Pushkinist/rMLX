//! DFlash 2 forward tests.
//!
//! Two oracles, because neither alone is enough.
//!
//! * **Analytic.** The convolution is applied to hand-built weights whose
//!   answer is a closed form written out in the test. This is what pins the
//!   things a plausible-looking hidden state hides: which tap reads the
//!   previous position, that the tap reaching before the block reads zero, that
//!   the base term is per channel while the correction is per group, and that
//!   one projection carries both sides in that order.
//! * **The reference implementation.** `tests/fixtures/dflash2_scale` holds a
//!   small synthetic drafter snapshot and the hidden states the z-lab MLX
//!   reference produces from it, for three shapes of input. It is generated by
//!   the `generate.py` beside it. This is what pins the whole stack — the
//!   conditioning projection, the norms, RoPE, the sliding mask and the MLP —
//!   against something other than this port's own opinion.
//!
//! Everything here runs on the CPU device and needs no model snapshot, so it
//! runs under `make test` rather than only where a checkpoint happens to be.

use std::path::{Path, PathBuf};

use rmlx_mlx::Dtype;

use super::*;
use crate::layers::Linear;

/// Where the reference snapshot and its expected outputs live.
const FIXTURE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/dflash2_scale");

/// The scale model's width, matching the fixture's `config.json`.
const SCALE_HIDDEN: usize = 64;

/// Largest absolute difference from the reference this port is allowed: one
/// bf16 unit in the last place at the magnitude these hidden states reach.
///
/// Both sides run the same MLX ops in bf16 on the same device, so the only
/// difference left is rounding — the reference masks with a boolean where this
/// port adds a large-negative bias, and it rotates its conditioning rows at the
/// drafter cache's absolute offset where this port rotates them from zero. All
/// three cases land exactly here and no further; the reference's own answer
/// moves by the same one place between two absolute offsets that are
/// mathematically identical. The cases are 0.60 apart, ~37x this bound.
const REFERENCE_TOL: f32 = 0.016;

