//! Tests for the iso3 KV-cache CPU codec.
//!
//! # Python gold fixture
//!
//! The bit-exact quaternion fixture values were generated offline using the
//! Python script below (pure Python, no torch dependency):
//!
//! ```python
//! # scripts/gen_isoquant_fixture.py
//! # q = [1.0, 0.5, -0.3, 0.2]   (not a unit quaternion — just a test vector)
//! # v = [0.1, -0.4, 0.9, 0.6]
//! # Hamilton product from rotorquant/turboquant/isoquant.py::quat_multiply
//! q = [1.0, 0.5, -0.3, 0.2]
//! v = [0.1, -0.4, 0.9, 0.6]
//! aw, ax, ay, az = q
//! bw, bx, by, bz = v
//! rw = aw*bw - ax*bx - ay*by - az*bz  # 0.45
//! rx = aw*bx + ax*bw + ay*bz - az*by  # -0.71
//! ry = aw*by - ax*bz + ay*bw + az*bx  # 0.49
//! rz = aw*bz + ax*by - ay*bx + az*bw  # 0.95
//! print(rw, rx, ry, rz)
//! # Output: 0.45 -0.71 0.49 0.95
//! ```
//!
//! Verified: Python float64 outputs match f32 within 1e-6 for these clean
//! rational inputs. The Rust test pins against the exact analytical values.

use crate::isoquant::{
    iso_decode_fast, iso_encode_fast, quat_conjugate, quat_multiply, IsoQuantError, FIXED_QUAT,
};
use crate::test_utils::{cosine_similarity_per_row, lcg_data, TEST_SEED};

// ── Bit-exact quaternion fixture ─────────────────────────────────────────────

/// Verify `quat_multiply` matches Python `isoquant.py::quat_multiply` to f32 precision.
///
/// Gold values generated by `scripts/gen_isoquant_fixture.py` (see module doc).
/// Inputs are clean rational values chosen so that Python float64 and Rust f32
/// intermediate results agree to better than 1e-6.
///
/// Python output (float64): `rw=0.45, rx=-0.71, ry=0.49, rz=0.95`
/// All four values are exact rational multiples with no f64→f32 rounding error
/// at these magnitudes.
#[test]
fn quaternion_hamilton_matches_python_bit_exact() {
    // q = [1.0, 0.5, -0.3, 0.2], v = [0.1, -0.4, 0.9, 0.6]
    // Not unit quaternions — just selected for clean arithmetic.
    let q = [1.0_f32, 0.5, -0.3, 0.2];
    let v = [0.1_f32, -0.4, 0.9, 0.6];

    let r = quat_multiply(q, v);

    // Gold values (Python script output pinned):
    // rw = aw*bw - ax*bx - ay*by - az*bz = 1.0*0.1 - 0.5*(-0.4) - (-0.3)*0.9 - 0.2*0.6
    //    = 0.1 + 0.2 + 0.27 - 0.12 = 0.45
    // rx = aw*bx + ax*bw + ay*bz - az*by = 1.0*(-0.4) + 0.5*0.1 + (-0.3)*0.6 - 0.2*0.9
    //    = -0.4 + 0.05 - 0.18 - 0.18 = -0.71
    // ry = aw*by - ax*bz + ay*bw + az*bx = 1.0*0.9 - 0.5*0.6 + (-0.3)*0.1 + 0.2*(-0.4)
    //    = 0.9 - 0.3 - 0.03 - 0.08 = 0.49
    // rz = aw*bz + ax*by - ay*bx + az*bw = 1.0*0.6 + 0.5*0.9 - (-0.3)*(-0.4) + 0.2*0.1
    //    = 0.6 + 0.45 - 0.12 + 0.02 = 0.95
    let expected = [0.45_f32, -0.71, 0.49, 0.95];
    let tol = 1e-6_f32; // tighter than 1e-5; f32 epsilon for these values is ~5e-8

    for (i, (&got, &exp)) in r.iter().zip(expected.iter()).enumerate() {
        assert!(
            (got - exp).abs() < tol,
            "component {i}: got {got:.10e}, expected {exp:.10e}, diff {:.2e} > tol {tol:.2e}",
            (got - exp).abs()
        );
    }
}

// ── Determinism gate ──────────────────────────────────────────────────────────

/// Encode → decode → encode again; assert codes are bit-identical between passes.
///
/// This verifies that `iso_encode_fast` is purely deterministic: no hidden RNG,
/// no mutable state, identical output for identical input.
#[test]
fn iso_encode_decode_roundtrip_determinism() {
    let head_dim = 64;
    let group_size = 4;
    let bits = 3;
    let n_tokens = 8;

    let data = lcg_data(n_tokens * head_dim, TEST_SEED);

    // First encode.
    let (codes1, scales1, quats1, norms1) =
        iso_encode_fast(&data, head_dim, group_size, bits).unwrap();

    // Decode.
    let decoded = iso_decode_fast(
        &codes1, &scales1, &quats1, &norms1, head_dim, group_size, bits,
    )
    .unwrap();

    // Second encode of decoded output.
    let (codes2, _scales2, _quats2, _norms2) =
        iso_encode_fast(&decoded, head_dim, group_size, bits).unwrap();

    // Codes must be bit-identical (determinism gate).
    assert_eq!(
        codes1.len(),
        codes2.len(),
        "codes length mismatch between passes"
    );
    for (i, (&c1, &c2)) in codes1.iter().zip(codes2.iter()).enumerate() {
        assert_eq!(
            c1, c2,
            "codes differ at word {i}: first pass {c1:#010x} vs second pass {c2:#010x}"
        );
    }
}

