// ── group_size divisibility guard ────────────────────────────────────────────

/// `group_size` that does not divide `head_dim` must return `GroupSizeNotDivisorOfHeadDim`.
///
/// Example: head_dim=64, group_size=24 → 64 % 24 = 16 ≠ 0.
/// Without this guard, n_groups = 64/24 = 2 (truncated), leaving 16 elements
/// silently unquantized and returning under-sized output buffers as success.
#[test]
fn iso_encode_invalid_group_size_returns_err() {
    // head_dim=64, group_size=24: 24 divides by 4 (valid multiple-of-4) but
    // 64 % 24 = 16 ≠ 0 — not a divisor of head_dim.
    let head_dim = 64_usize;
    let group_size = 24_usize;
    let data = vec![0.0_f32; head_dim]; // 1 token
    let result = iso_encode_fast(&data, head_dim, group_size, 3);
    match result {
        Err(IsoQuantError::GroupSizeNotDivisorOfHeadDim {
            group_size: 24,
            head_dim: 64,
        }) => {} // expected
        other => panic!(
            "expected GroupSizeNotDivisorOfHeadDim(group_size=24, head_dim=64), got {other:?}"
        ),
    }
}

// ── Cosine gate ───────────────────────────────────────────────────────────────

/// iso3 cosine-similarity gate on LCG fixture data.
///
/// Setup: 32 tokens × 128-dim, group_size=4, bits=3.
/// LCG seed: `TEST_SEED` (pinned; must stay reproducible).
///
/// Measured cosine (first run, LCG fixture, Gaussian Lloyd codebook):
///   mean = 0.9941, min = 0.9932
///
/// Threshold is set at `measured_mean − 0.001` to guard against regression.
///
/// # Gap vs mtq published benchmark
///
/// The Python mtq reference reports cosine ≈ 0.9783 for iso3 on realistic KV
/// vectors from calibrated Llama-3 layers. Our LCG fixture yields higher cosine
/// (0.9941 mean) because:
///
///   1. LCG data has lower dynamic range than real KV activations.
///   2. rMLX uses `group_size=4` (one quaternion block per group) vs mtq's
///      larger group sizes; smaller groups give finer-grained scales.
///
/// These are different measurement conditions — the comparison is informational
/// only. Regression is gated against the measured LCG value, not vs mtq.
///
/// # Codebook divergence note
///
/// Python reference (rotorquant + mtq) uses Beta Lloyd-Max optimal codebook.
/// rMLX uses Gaussian Lloyd-Max (N(0,1)) from `turboquant::lloyd_gaussian_codebook(3)`.
/// For head_dim ≥ 64 the distributions converge; the quality gap is negligible
/// on LCG fixture and measured below the −0.001 regression margin.
#[test]
fn iso3_cosine_gate() {
    let n_tokens = 32;
    let head_dim = 128;
    let group_size = 4;
    let bits = 3;

    let data = lcg_data(n_tokens * head_dim, TEST_SEED);

    let (codes, scales, quats, norms) = iso_encode_fast(&data, head_dim, group_size, bits).unwrap();
    let decoded =
        iso_decode_fast(&codes, &scales, &quats, &norms, head_dim, group_size, bits).unwrap();

    let stats = cosine_similarity_per_row(&data, &decoded, head_dim);

    // Threshold = measured_mean − 0.001 (empirical floor).
    // Measured on first run: mean = 0.9941, min = 0.9932.
    // Update these constants if the codebook or algorithm changes (bump the
    // measured values and re-set threshold = new_mean - 0.001).
    let threshold_mean = 0.993_0_f32;
    let threshold_min = 0.992_0_f32;

    assert!(
        stats.mean >= threshold_mean,
        "iso3 cosine mean {:.6} fell below threshold {threshold_mean:.6} (n_rows={})",
        stats.mean,
        stats.n_rows,
    );
    assert!(
        stats.min >= threshold_min,
        "iso3 cosine min {:.6} fell below threshold {threshold_min:.6} (n_rows={})",
        stats.min,
        stats.n_rows,
    );

    // Diagnostic: print so the measured value appears in `cargo test -- --nocapture`
    println!(
        "iso3 cosine: mean={:.6}, min={:.6}, n_rows={} (threshold mean>={threshold_mean:.6}, min>={threshold_min:.6})",
        stats.mean, stats.min, stats.n_rows,
    );
}

