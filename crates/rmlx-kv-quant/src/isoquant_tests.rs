// ── Quaternion conjugate sanity ───────────────────────────────────────────────

/// `q * q̄ = (1, 0, 0, 0)` for a unit quaternion (within f32 tolerance).
#[test]
fn quat_conjugate_times_self_is_identity() {
    let q = FIXED_QUAT;
    let q_conj = quat_conjugate(q);
    let result = quat_multiply(q, q_conj);
    // Should be very close to (1, 0, 0, 0)
    assert!(
        (result[0] - 1.0).abs() < 1e-6,
        "w component should be ~1.0, got {}",
        result[0]
    );
    for &v in &result[1..] {
        assert!(v.abs() < 1e-6, "imaginary component should be ~0, got {v}");
    }
}

/// The fixed quaternion must be unit-length (within f32 tolerance).
#[test]
fn fixed_quat_is_unit_length() {
    let q = FIXED_QUAT;
    let norm_sq: f32 = q.iter().map(|&x| x * x).sum();
    assert!(
        (norm_sq - 1.0).abs() < 1e-5,
        "FIXED_QUAT norm_sq={norm_sq:.8} should be ~1.0"
    );
}
